class KernelListEntries(NamedTuple):
    """Entries found in the lines of a kernel list."""

    files: list[str]
    options: list[str]
    num_file: int
    num_opti: int
    num_desc: int


class KernelList:
    """Class to generate a Kernel List.

    :param setup: NPB execution setup object
    """

    def __init__(self, setup) -> None:
        """Constructor."""
        self.complete_list = ''
        self.files = []
        self.kernel_list = []
        self.list_name = ''
        self.setup = setup

        #
        # Entity attributes to be replaced in template
        #
        self.CURRENTDATE = str(datetime.datetime.now())[:10]
        self.OBS = setup.observer
        self.AUTHOR = setup.producer_name

        if self.setup.pds_version == "3":
            if '"' in setup.pds3_mission_template["DATA_SET_ID"]:
                self.DATA_SET_ID = (
                    setup.pds3_mission_template["DATA_SET_ID"].split('"')[1].upper()
                )
            else:
                self.DATA_SET_ID = setup.pds3_mission_template["DATA_SET_ID"].upper()
            self.VOLID = setup.volume_id.lower()
        else:
            self.DATA_SET_ID = "N/A"
            self.VOLID = "N/A"

        self.RELID = f"{int(setup.release):04d}"
        self.RELDATE = setup.release_date

        self.template = f"{setup.templates_directory}/template_kernel_list.txt"
        self.read_config()

    def add(self, kernel: str) -> None:
        """Add SPICE kernel or OrbNum file to the list.

        :param kernel: SPICE kernel or OrbNum file added to the list
        """
        self.files.append(kernel)

    def read_config(self) -> None:
        """Extract the Kernel List information from the configuration file."""
        json_config = self.setup.kernel_list_config

        self.re_config = self.setup.re_config
        self.json_config = json_config

        json_formatted_str = json.dumps(self.json_config, indent=2)
        self.json_formatted_lst = json_formatted_str.split("\n")

    @spice_exception_handler
    def write_list(self):
        """Write the Kernel List product.

        The list is not an archival product but an NPB by-product, therefore
        it is not generated by any of the product classes.
        """
        list_name = (
            f"{self.setup.mission_acronym}_{self.setup.run_type}_"
            f"{int(self.setup.release):02d}.kernel_list"
        )

        list_dictionary = vars(self)

        self._fill_template(
            self.setup.working_directory + os.sep + list_name, list_dictionary
        )

        with open(self.setup.working_directory + os.sep + list_name, "a+", encoding='utf-8') as f:

            for kernel in self.kernel_list:
                ker_added_to_list = False
                #
                # Find the correspondence of the filename in the JSON file
                #
                for pattern in self.re_config:

                    if pattern.match(kernel):

                        #
                        # Description is the only mandatory field.
                        #
                        description = self.json_config[pattern.pattern]["description"]

                        try:
                            options = self.json_config[pattern.pattern][
                                "mklabel_options"
                            ]

                        # "mklabel_options" is an optional config key.
                        except KeyError:
                            options = ""

                        try:
                            patterns = self.json_config[pattern.pattern]["patterns"]

                        # "patterns" is an optional config key.
                        except KeyError:
                            patterns = False

                        try:
                            mapping = self.json_config[pattern.pattern]["mapping"]
                        # "mapping" is an optional config key.
                        except KeyError:
                            mapping = ""

                        #
                        # "options" and "descriptions" require to substitute parameters derived from the filenames
                        # themselves or from the comments of the kernel.
                        #
                        if patterns:
                            for el in patterns:
                                if f'${el}' in description or f'${el}' in mapping:
                                    value = patterns[el]

                                    #
                                    # There are two distinct patterns:
                                    #    * extracted form the filename
                                    #    * defined in the configuration file.
                                    #
                                    if (
                                        "@pattern" in patterns[el]
                                        and patterns[el]["@pattern"].lower() == "kernel"
                                    ):
                                        #
                                        # When extracted from the filename, the keyword  is matched in between patterns.
                                        #

                                        #
                                        # First Turn the regex set into a single character to be able to know were in
                                        # the filename is.
                                        #
                                        patt_ker = value["#text"].replace("[0-9]", "$")
                                        patt_ker = patt_ker.replace("[a-z]", "$")
                                        patt_ker = patt_ker.replace("[A-Z]", "$")
                                        patt_ker = patt_ker.replace("[a-zA-Z]", "$")

                                        #
                                        # Split the resulting pattern to build up the indexes to extract the value
                                        # from the kernel name.
                                        #
                                        patt_split = patt_ker.split(f"${el}")

                                        #
                                        # Create a list with the length of each part.
                                        #
                                        indexes = []
                                        for element in patt_split:
                                            indexes.append(len(element))

                                        #
                                        # Extract the value with the index from the kernel name.
                                        #
                                        # TODO: This indexes work because the mapping kernel and the resulting kernel are in the same place!
                                        if len(indexes) == 2:
                                            value = kernel[
                                                indexes[0] : len(kernel) - indexes[1]
                                            ]
                                            if patterns[el]["@pattern"].isupper():
                                                value = value.upper()
                                        else:
                                            raise NPBError(
                                                f"Kernel pattern for {kernel} not adept to write description. Remember a "
                                                "metacharacter cannot start or finish a kernel pattern."
                                            )

                                        if mapping:
                                            mapping = mapping.replace("$" + el, value)

                                    elif (
                                        "@file" in patterns[el]
                                        and patterns[el]["@file"].lower() == "comment"
                                    ):
                                        #
                                        # Extracting the value from the comment
                                        # area of the kernel. This is usually to
                                        # get the original kernel name.
                                        #
                                        # So far this method is implemented to accomodate MRO files
                                        #
                                        comment = extract_comment(
                                            self.setup.kernels_directory[0]
                                            + f"/{ extension_to_type(kernel.split('.')[-1])}/"
                                            + kernel
                                        )

                                        for line in comment:
                                            if patterns[el]["#text"] in line:
                                                value = line.strip()
                                                break

                                        if not isinstance(value, str):
                                            raise NPBError(
                                                f"Kernel pattern not found in comment area of {kernel}."
                                            )

                                    else:
                                        #
                                        # For non-kernels the value is based
                                        # on the value within the tag that
                                        # needs to be provided by the user;
                                        # there is no way this can be done
                                        # automatically.
                                        #

                                        #
                                        # First we convert into a list in
                                        # case there is just one
                                        #
                                        patterns_el = patterns[el]
                                        if not isinstance(patterns_el, list):
                                            patterns_el = [patterns_el]
                                        for val in patterns_el:
                                            try:
                                                if val["@value"] in kernel:
                                                    value = val["#text"]
                                            except KeyError:
                                                raise NPBError(
                                                    f"Error generating kernel list with {kernel}. "
                                                    f"Consider reviewing your NPB setup."
                                                )

                                        if isinstance(value, (list, dict)):
                                            raise NPBError(
                                                f"-- Kernel {kernel} description could not be updated with "
                                                f"pattern."
                                            )

                                    description = description.replace("$" + el, value)

                        if options:
                            for option in options.split():
                                if '$PHASES' in option:
                                    if hasattr(self.setup, "phases"):
                                        if list(self.setup.phases.keys())[0]:
                                            phases = self.setup.phases["phase"]["@name"]
                                        else:
                                            phases = "N/A"
                                    else:
                                        phases = "N/A"

                                    options = options.replace("$PHASES", phases)

                        #
                        # Reformat the description, given that format of the XML file is not restrictive (spaces or
                        # newlines might be present).
                        #
                        description = description.replace("\n", " ")
                        description = " ".join(description.split())

                        if self.setup.pds_version == "3":
                            kerdir = "data/" + extension_to_type(kernel)
                        else:
                            kerdir = "spice_kernels/" + extension_to_type(kernel)

                        if not options:
                            options = ""

                        f.write(f"FILE             = {kerdir}/{kernel}\n")
                        #
                        # Introduced to avoid trailing white space.
                        #
                        if not options:
                            f.write("MAKLABEL_OPTIONS =\n")
                        else:
                            f.write(f"MAKLABEL_OPTIONS = {options}\n")
                        f.write(f"DESCRIPTION      = {description}\n")

                        if mapping:

                            logging.info('-- Mapping %s with %s', kernel, mapping)

                            f.write(f"MAPPING          = {mapping}\n")

                        ker_added_to_list = True

                if not ker_added_to_list:
                    f.write(f"FILE             = miscellaneous/orbnum/{kernel}\n")
                    f.write("MAKLABEL_OPTIONS = N/A\n")
                    f.write("DESCRIPTION      = N/A\n")

        self.list_name = list_name

        self.validate()

    def read_list(self, kerlist):
        """Read the Kernel List.

        Note that the format that the kernel list has to follow is very
        strict, including no whitespace at the end of each line and Line-feed
        EOL.

        :param kerlist: Kernel List path
        :type kerlist: str
        """
        kernel_list = (
            f"{self.setup.working_directory}{os.sep}"
            f"{self.setup.mission_acronym}_{self.setup.run_type}_"
            f"{int(self.setup.release):02d}.kernel_list"
        )

        try:
            shutil.copy2(kerlist, kernel_list)
        except shutil.SameFileError:
            pass

        self.list_name = kernel_list.split(os.sep)[-1]

        #
        # Generate the kernel list attribute, necessary for the validation.
        #
        kernels = []
        with open(kernel_list, "r", encoding='utf-8') as lst:
            for line in lst:
                if "FILE             =" in line:
                    kernels.append(line.split(os.sep)[-1].rstrip("\r\n"))

        self.kernel_list = kernels

        self.validate()

    def write_complete_list(self):
        """Write the complete Kernel List using the former ones."""
        kernel_lists = glob.glob(
            self.setup.working_directory
            + os.sep
            + f"{self.setup.mission_acronym}_release*"
            f".kernel_list"
        )

        #
        # Sort list in inverse order in such way that the DATASETID is
        # obtained from the header of the latest list.
        #
        kernel_lists.sort(reverse=True)

        complete_list = f"{self.setup.mission_acronym}_complete.kernel_list"

        release_list = []
        with open(self.setup.working_directory + os.sep + complete_list, "w+", encoding='utf-8') as c:
            for kernel_list in kernel_lists:

                logging.info('-- Adding %s', kernel_list)

                token = kernel_list.replace("_", ".").split(".")[-3]
                try:
                    release_list.append(int(token))
                except ValueError:
                    raise NPBError(
                        f"Non-numeric release token '{token}' in kernel list filename "
                        f"'{os.path.basename(kernel_list)}'."
                    )
                with open(kernel_list, "r", encoding='utf-8') as lst:
                    for line in lst:
                        c.write(line)

        try:
            if not self._check_consecutive(release_list):
                logging.warning('-- Incomplete Kernel lists available: %s', release_list)
        except ValueError:
            raise NPBError('-- No release kernel lists available.')

        self.complete_list = complete_list

        self.validate_complete()

    def validate(self):
        """Validation of the Kernel List.

        The validation of the Kernel List performs the following checks:

         * check that the list has the same number of ``FILE``, ``MAKLABEL_OPTIONS``,
           and ``DESCRIPTION`` entries.
         * check list against plan
         * check that list for duplicate files
         * check that all files listed in the list are on the ``kernels_directory``
         * check that the files are not in the ``bundle_directory``
         * display all the ``MAKLABL_OPTIONS`` used
         * check that all the ``MAKLBL_OPTIONS`` are in the template for PDS3
         * check that the list has no duplicates
         * check that the list has no bad characters
         * if the ``-d DIFF --diff DIFF`` argument is used, compare the kernel
           list with the kernel list of the previous release -if avaialble.
        """
        list_path = self.setup.working_directory + os.sep + self.list_name

        #
        # Check that the list has no bad characters.
        # This does not raise an error message but does not stop NPB.
        #
        errors = self._check_badchar(list_path)
        if errors:

            for err in errors:
                logging.error('   %s', err)

        with open(list_path, "r", encoding='utf-8') as lst:

            #
            # Check that the list has the same number of FILE,
            # MAKLABEL_OPTIONS, and DESCRIPTION entries
            #
            entries = self._parse_entries(lst)
            num_file = entries.num_file
            num_opti = entries.num_opti
            num_desc = entries.num_desc

            #
            # We add kernels to compare plan and list and to look
            # for duplicates.
            #
            ker_in_list = entries.files

            #
            # We add options to display and compare to template. The parser
            # also returns the 'None' tokens, which are not options.
            #
            opt_in_list = [opt for opt in entries.options if opt != "None"]

            if (num_file != num_opti) or (num_opti != num_desc):

                error = "List does not have the same number of entries"

                logging.error('%s for:', error)
                logging.error('   FILE             (%d)', num_file)
                logging.error('   MAKLABEL_OPTIONS (%d)', num_opti)
                logging.error('   DESCRIPTION      (%d)', num_desc)
                logging.error('')

                logging.error(
                    '-- Display %s kernel list configuration file to'
                    ' double-check.', self.setup.mission_name)

                for line in self.json_formatted_lst:
                    logging.info(line)
                logging.error("")

                raise Exception(error)

            #
            # Check list against plan.
            #
            for ker in ker_in_list:
                if ker not in self.kernel_list:
                    raise NPBError(f"   {ker} not in list.")

            #
            # Check list for duplicate entries.
            #
            if check_list_duplicates(ker_in_list):
                raise NPBError("List contains duplicates.")

            #
            # Check that all files listed are available in OPS area;
            # This does not raise an error but only a warning.
            #
            logging.info("-- Checking that kernels are present in: ")

            for work_dir in self.setup.kernels_directory:
                logging.info('   %s', work_dir)

            # TODO: BUG, 'present' is initialised outside the loop and is never
            #       reset by the kernel, if an existing kernel is found, all
            #       kernels processed afterwards—even if they do not exist—will
            #       be listed anyway and will not trigger any WARNING. In other
            #       words, the behaviour depends on the order in which the
            #       kernels are processed.
            present = False
            all_present = True
            for ker in ker_in_list:
                for work_dir in self.setup.kernels_directory:
                    #
                    # We cannot assume that the file is under a certain
                    # directory, it can be in any sub-directory.
                    #
                    file = [
                        os.path.join(root, name)
                        for root, dirs, files in os.walk(work_dir)
                        for name in files
                        if name == ker
                    ]
                    if file:
                        present = True
                if not present:
                    if ".tm" in ker:
                        logging.info('     %s not present as expected.', ker)

                    else:
                        logging.warning(
                            '     %s not present. Kernel might be mapped.', ker)

                        all_present = False
            if all_present:
                logging.info("     All kernels present.")
            logging.info("")

            #
            # Check that no file is in the final area.
            #
            present = False

            logging.info('-- Checking that kernels are present in %s: ',
                         self.setup.bundle_directory)

            for ker in ker_in_list:
                if os.path.isfile(
                    self.setup.bundle_directory
                    + f"/{self.setup.mission_acronym}_spice/"
                    f"spice_kernels/" + extension_to_type(ker) + os.sep + ker
                ):
                    present = True

                    logging.warning('     %s present.', ker)

            if not present:
                logging.info("     No kernels present in final area.")
            logging.info("")

            #
            # IF you generate a PDS23 data set, display all the MAKLABL_OPTIONS
            # used
            #
            if self.setup.pds_version == "3":
                opt_in_list = list(dict.fromkeys(opt_in_list))
                opt_in_list.sort()
                logging.info("-- Display all the MAKLABEL_OPTIONS:")

                for option in opt_in_list:
                    logging.info('     %s', option)

                logging.info('')

            #
            # The PDS Mission Template file is not required for PDS4
            #
            if self.setup.pds_version == "3":
                logging.info(
                    "-- Check that all template tags used in the list are present in template:"
                )

                maklabel_options = self.setup.pds3_mission_template[
                    "maklabel_options"
                ].keys()

                for option in opt_in_list:

                    if option in maklabel_options:
                        logging.info('     %s is present.', option)

                    else:
                        if option != "N/A":
                            raise NPBError(f"{option} not in configuration.")

                logging.info('')

            #
            # Check complete list for duplicate entries
            #
            logging.info("-- Checking for duplicates in complete kernel list:")

            kernel_lists = glob.glob(
                self.setup.working_directory
                + os.sep
                + f"{self.setup.mission_acronym}_release*"
                f".kernel_list"
            )
            kernel_lists.sort()

            ker_in_list = []
            for kernel_list in kernel_lists:

                with open(kernel_list, "r", encoding='utf-8') as lst:

                    #
                    # Check that the list has the same number of FILE,
                    # MAKLABEL_OPTIONS, and DESCRIPTION entries
                    #
                    logging.info('     Adding %s in check.', kernel_list)

                    ker_in_list.extend(self._parse_entries(lst).files)

            if check_list_duplicates(ker_in_list):
                raise NPBError("List contains duplicates.")
            else:
                logging.info("     List contains no duplicates.")
            logging.info("")

        if self.setup.args.diff and self.setup.increment:
            #
            # Compare list with previous list
            #
            logging.info("-- Comparing current list with previous list:")

            logging.info("")

            # An empty glob means the current list itself is missing; a single
            # entry means there is just no previous list to compare it with.
            if not kernel_lists:
                logging.error("-- Current list not available.")

            else:
                fromfile = kernel_lists[-1]

                try:
                    tofile = kernel_lists[-2]
                    work_dir = self.setup.working_directory
                    compare_files(fromfile, tofile, work_dir,
                                  self.setup.args.diff)

                # kernel_lists[-2] raises IndexError; compare_files() raises
                # OSError/UnicodeDecodeError on a bad file.
                except (IndexError, *FILE_READ_ERRORS):
                    logging.error("-- Previous list not available.")

    def validate_complete(self):
        """Validation of the complete Kernel List.

        The complete Kernel List is generated by NPB by merging all the
        available Kernel List files. These kernel list files must be located
        in the ``working_directory`` as specified by the NPB configuration.

        In principle all the kernels that have ever been added to the archive
        should be present.

        The validation of the complete Kernel List performs the following checks:

         * check that the list has the same number of ``FILE``, ``MAKLABEL_OPTIONS``,
           and ``DESCRIPTION`` entries
         * check all the ``MAKLABL_OPTIONS`` used
         * check that the list has no duplicates
        """
        num_file = 0
        num_opti = 0
        num_desc = 0

        ker_in_list = []
        opt_in_list = []

        with open(
            self.setup.working_directory + os.sep + self.complete_list, "r", encoding='utf-8'
        ) as lst:

            #
            # Check that the list has the same number of FILE,
            # MAKLABEL_OPTIONS, and DESCRIPTION entries
            #
            logging.info("-- Checking list number of entries coherence:")

            for line in lst:

                # TODO: BUG; entry type is detected with substring ('in')
                #       tests instead of prefix checks. Any DESCRIPTION or
                #       OPTIONS line whose text contains the word 'FILE'
                #       (e.g. "DESCRIPTION = FILE naming kernel") is
                #       miscounted as an extra FILE entry, causing the
                #       coherence check to raise on a perfectly valid list.
                #       The same flaw applies to 'OPTIONS' and 'DESCRIPTION'.
                if ("FILE" in line) and (line.split("=")[-1].strip()):
                    num_file += 1
                    #
                    # We add kernels to compare plan and list and to look
                    # for duplicates.
                    #
                    ker_in_list.append(line.split("/")[-1].strip())

                elif "OPTIONS" in line:
                    num_opti += 1
                    #
                    # We add options to display and compare to template
                    #
                    options = line.split("=")[-1].split()
                    for option in options:
                        opt_in_list.append(option)

                elif ("DESCRIPTION" in line) and (line.split("=")[-1].strip()):
                    num_desc += 1

            if (num_file != num_opti) or (num_opti != num_desc):
                error = "List does not have the same number of entries"

                logging.error('%s for:', error)
                logging.error('   FILE             (%d)', num_file)
                logging.error('   MAKLABEL_OPTIONS (%d)', num_opti)
                logging.error('   DESCRIPTION      (%d)', num_desc)
                logging.error('')

                logging.error('-- Display %s kernel list configuration file to'
                              ' double-check.', self.setup.mission_name)

                for line in self.json_formatted_lst:
                    logging.info(line)
                logging.error("")

                raise Exception(error)

            logging.info('     PASS with total of %d entries.', num_file)
            logging.info('')

            #
            # Check list for duplicate entries
            #
            logging.info("-- Checking for duplicates in kernel list:")
            if check_list_duplicates(ker_in_list):
                raise NPBError("List contains duplicates.")
            else:
                logging.info("     List contains no duplicates.")
            logging.info("")

            #
            # Display all the MAKLABL_OPTIONS used if archive is PDS3.
            #
            if self.setup.pds_version == "3":
                opt_in_list = list(dict.fromkeys(opt_in_list))
                opt_in_list.sort()
                logging.info("-- Display all the MAKLABEL_OPTIONS:")

                for option in opt_in_list:
                    logging.info('     %s', option)

                logging.info('')

            #
            # The PDS Mission Template file is not required for PDS4
            #
            if self.setup.pds_version == "3":
                logging.info(
                    "-- Check that all template tags used in the "
                    "list are present in template:"
                )
                # TODO: BUG; the template path is built with a hardcoded forward
                #       slash instead.
                template = (
                    self.setup.root_dir + f"/config/{self.setup.mission_acronym}"
                    f"_mission_template.pds"
                )
                with open(template, "r", encoding='utf-8') as o:
                    template_lines = o.readlines()

                for option in opt_in_list:
                    present = False
                    for line in template_lines:
                        if "--" + option in line:
                            present = True
                    if present:
                        logging.info('     %s is present.', option)

                    else:
                        raise NPBError(f"{option} not in template.")

                logging.info('')

    def check_products(self):
        """Check the SPICE kernel and ORBNUM products from the kernel list.

        The products present in the Kernel List --whether if generated by NPB
        or provided by the user-- will be checked and if issues are found they
        will be reported as ``WARNING`` or ``ERROR`` messages.

        The checks performed to the products are the following:

         * identify if a SPICE kernel is present in multiple kernel directories
         * check End of Line character for text SPICE kernels and ORBNUM files.
         * check text SPICE kernels and ORBNUM files for non-ASCII characters.
         * check if text SPICE kernels have more than 80 characters per line.
         * validate kernel architecture
         * check endianness and permissions of binary kernels
        """
        # A products errors list and a warnings list will be created these
        # will be stored in a product dictionary. The error list will stop
        # the execution while the warnings list will only display warning
        # messages in the log.
        #
        product_errors = {}
        product_warnings = {}

        product_list = self.kernel_list

        for product in product_list:

            product_errors[product] = []
            product_warnings[product] = []

            #
            # Check if a product is present in multiple directories
            #
            # The origin_paths is a list that contains all the locations of
            # the product. In the case of an ORBNUM file it can only be one.
            #
            origin_paths = []

            #
            # Identify the path(s) of each product.
            #
            if (".nrb" in product.lower()) or (".orb" in product.lower()):
                origin_paths.append(self.setup.orbnum_directory + os.sep + product)
            else:
                for directory in self.setup.kernels_directory:
                    try:
                        file = [
                            os.path.join(root, ker)
                            for root, dirs, files in os.walk(directory)
                            for ker in files
                            if product == ker
                        ]
                        origin_paths.append(file[0])

                    # file[0] raises IndexError when no file matched the product
                    # name.
                    except IndexError:

                        try:
                            file = [
                                os.path.join(root, ker)
                                for root, dirs, files in os.walk(directory)
                                for ker in files
                                if product_mapping(product, self.setup, cleanup=False)
                                == ker
                            ]
                            origin_paths.append(file[0])

                        # file[0] raises IndexError with no mapped-name match;
                        # product_mapping() opens the kernel_list with
                        # encoding='utf-8', so it can raise OSError if the
                        # file doesn't exist yet or UnicodeDecodeError if
                        # it's not valid UTF-8; ValueError if setup.release
                        # isn't a valid integer.
                        except (IndexError, ValueError, *FILE_READ_ERRORS):
                            pass

            if not origin_paths and ".tm" not in product.lower():
                product_errors[product].append(
                    "Product not present in any kernel directory(ies)"
                )
                continue

            if not origin_paths and ".tm" in product.lower():
                product_warnings[product].append(
                    "Meta-kernel will be generated during this run."
                )
                continue

            if len(origin_paths) > 1:
                product_warnings[product].append(
                    "Product present in multiple directories:"
                )
                for path in origin_paths:
                    product_warnings[product].append(f"  {path}")
                product_warnings[product].append(
                    "The product in the first directory will be used."
                )

            #
            # From here on the product present in the first directory from
            # configuration will be checked.
            #
            origin_path = origin_paths[0]

            # Check that file has read permissions.
            self._check_permissions(origin_path)

            #
            # Check bad characters and EOL for text kernels and ORBNUM files.
            # Check line length < 80 for text kernels.
            #
            if product.split(".")[-1].strip()[0].lower() != "b":
                if (".nrb" not in product.lower()) and (".orb" not in product.lower()):
                    eol = "\n"
                elif (
                    (".nrb" in product.lower()) or (".orb" in product.lower())
                ) and self.setup.pds_version == "3":
                    eol = "\n"
                else:
                    eol = self.setup.eol

                error = check_eol(origin_path, eol)
                if error:
                    if (".nrb" in product.lower()) or (".orb" in product.lower()):
                        product_warnings[product].append(error)
                    else:
                        product_errors[product].append(error)

                error = self._check_badchar(origin_path)
                if error:
                    product_warnings[product] += error

                if (".nrb" not in product.lower()) and (".orb" not in product.lower()):
                    error = check_line_length(origin_path)
                    if error:
                        product_warnings[product] += error

            #
            # Check Kernel architecture.
            #
            if ".nrb" not in product.lower() and ".orb" not in product.lower():
                error = self._check_kernel_integrity(origin_path)
                if error:
                    product_errors[product].append(error)

            # Check binary kernel endianness.
            if product.split(".")[-1].strip()[0].lower() == "b":
                # This step currently works only for PDS4 archives, and
                # disregards the configuration file's binary_endianness input
                # value.
                error = self._check_binary_endianness(
                    origin_path, endianness='little'
                )
                if error:
                    product_errors[product].append(error)

        #
        # With all checks performed now they need to be reported.
        # Start for logging and/or verbose mode reporting.
        #
        error_flag = False
        warning_flag = False
        for product in product_list:
            if product_errors[product] or product_warnings[product]:
                logging.warning('-- %s', product)

                warning_flag = True

                if product_warnings[product]:

                    for line in product_warnings[product]:
                        logging.warning('     %s', line)

                if product_errors[product]:
                    error_flag = True

                    for line in product_errors[product]:
                        logging.error('     %s', line)

        #
        # Report in standard output if necessary.
        #
        if not self.setup.args.silent and not self.setup.args.verbose:
            for product in product_list:
                if product_errors[product] or product_warnings[product]:
                    print(f"   * {product}")
                    warning_flag = True
                    if product_warnings[product]:
                        for line in product_warnings[product]:
                            print(f"     {line}")
                    if product_errors[product]:
                        error_flag = True
                        for line in product_errors[product]:
                            print(f"     {line}")

        if error_flag:
            if not self.setup.args.silent and not self.setup.args.verbose:
                print("-- Products listed above require work.")
            logging.error("")
            raise NPBError("Products listed above require work.")
        elif not warning_flag:
            logging.info("-- All products checks have succeeded.")
            logging.info("")
            if not self.setup.args.silent and not self.setup.args.verbose:
                print("-- All products checks have succeeded.")

    def _fill_template(
        self, product_file: str, product_dictionary: dict
    ) -> None:
        """Fill a template with uppercase keywords preceded with ``$``.

        :param product_file: Resulting file
        :param product_dictionary: Dictionary of keys to replace
        """
        with (open(product_file, "w", encoding='utf-8') as f,
              open(self.template, "r", encoding='utf-8') as t):
            for line in t:
                line = line.rstrip()
                for key, value in product_dictionary.items():
                    if isinstance(value, str) and key in line and "$" in line:
                        line = line.replace("$" + key, value)
                f.write(f"{line}\n")

    @staticmethod
    def _parse_entries(lines: Iterable[str]) -> KernelListEntries:
        """Classify the lines of a kernel list and collect their entries.

        The FILE basenames and the option tokens are returned in the order
        they appear. The option tokens are not filtered, so a ``None``
        token is returned like any other.

        :param lines: Lines of a kernel list
        :return: FILE basenames, option tokens and the number of FILE,
                 MAKLABEL_OPTIONS and DESCRIPTION entries
        """
        files = []
        options = []
        num_file = 0
        num_opti = 0
        num_desc = 0

        for line in lines:
            # TODO: BUG, when performing the check using substring, there is
            #       a possibility that a description may contain the word
            #       FILE. If this is the case, it would be counted
            #       incorrectly and, furthermore, the DESCRIPTION line would
            #       not be counted at all.
            if ("FILE" in line) and (line.split("=")[-1].strip()):
                num_file += 1
                files.append(line.split("/")[-1].strip())

            elif "OPTIONS" in line:
                num_opti += 1
                options.extend(line.split("=")[-1].split())

            elif ("DESCRIPTION" in line) and (line.split("=")[-1].strip()):
                num_desc += 1

        return KernelListEntries(files, options, num_file, num_opti, num_desc)

    @staticmethod
    def _check_consecutive(lst: list[int]) -> bool:
        """Check if a list has consecutive numbers.

        Check if a list of names with enumeration include all the elements
        in such a way that the enumeration contains all expected numbers.

        :param lst: List of names that include an enumeration
        :return: Check if the list has a complete enumeration
        """
        return sorted(lst) == list(range(1, max(lst) + 1))

    @staticmethod
    def _check_kernel_integrity(path: str) -> str:
        """Check if the SPICE Kernel has the adequate architecture and type.

        All SPICE kernels must have a NAIF file ID word as the first "word" on
        the first line of the kernel. This "word" describes the architecture
        and the type of the kernel.

        A binary kernel could have the following architectures:

          * ``DAF``: The file is based on the DAF architecture.
          * ``DAS``: The file is based on the DAS architecture.
          * ``XFR``: The file is in a SPICE transfer file format.

        For an archive both ``DAF`` and ``DAS`` are acceptable: SPKs, CKs and
        binary PCKs are DAF-based, whereas DSKs and binary EKs are DAS-based.
        Transfer format files are rejected.

        Text kernels must have ``KPL`` (Kernel Pool File) architecture.

        Whether a kernel is binary or text is determined from its extension
        (binary kernel extensions start with ``b``). In addition to the
        architecture, NPB checks that the kernel type in the file ID word
        matches the type expected from the kernel extension (e.g. ``SPK`` for
        ``.bsp``).

        **Note:** Text event kernels (``.ten``) are validated differently
        because they use a different format than other text kernels and are not
        loaded via standard SPICE routines. NPB only checks that they are
        UTF-8 encoded and that their first 2000 characters contain the
        ``\\header`` and ``\\text`` markers.

        :param path: SPICE Kernel path
        :return: Error message if error present, empty string otherwise
        """
        error = ""
        name = path.split(os.sep)[-1].strip()
        extension = path.split(".")[-1].strip().lower()

        # Filter out Text EKs since they are not loaded into SPICE and
        # validate them differently
        if extension == "ten":
            # Try to read the file as UTF-8
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    content = f.read(2000)
            except UnicodeDecodeError:
                return (f"Kernel {name} is not a valid text file "
                        f"(encoding error).")

            # Validate content after successful read
            if '\\header' not in content or '\\text' not in content:
                return (f"Kernel {name} does not contain required text event "
                        f"kernel markers (\\header, \\text).")

            return ""  # Valid .ten file

        type_file = extension_to_type(name).upper()

        #
        # Determine if it is a binary or a text kernel.
        #

        file_format = "Binary" if extension[0] == "b" else "Character"

        #
        # All files that are to have labels generated must have a NAIF
        # file ID word as the first "word" on the first line of the
        # file. Check if it is the case.
        #
        (arch, f_type) = spiceypy.getfat(path)

        if file_format == "Binary":

            #
            # A binary file could have the following architectures:
            #
            #   DAF - The file is based on the DAF architecture.
            #   DAS - The file is based on the DAS architecture.
            #   XFR - The file is in a SPICE transfer file format.
            #
            # For an archive both DAF and DAS (DSKs and binary EKs) are
            # acceptable.
            #
            if arch not in ('DAF', 'DAS'):
                error = f"Kernel {name} architecture {arch} is invalid."
            # else:
            #     pass

        else:  # file_format == "Character":

            #
            # Text kernels must have KPL architecture:
            #
            #    KPL -- Kernel Pool File (i.e., a text kernel)
            #
            if arch != "KPL":
                error = f"Kernel {name} architecture {arch} is invalid."

        if f_type != type_file:
            error = (f"Kernel {name} type {type_file} is not the one "
                     f"expected: {f_type}.")

        return error

    @staticmethod
    def _check_binary_endianness(path: str, endianness: str) -> Optional[str]:
        """Check if the SPICE Kernel has the adequate architecture.

        PDS4 Bundles require LTL-IEEE binary kernels and PDS3 data sets require
        BIG-IEEE binary kernels. This behavior can be changed via configuration.

        This method ensures that the endianness of binary kernels is the
        appropriate one according to the configuration.

        :param path:       Binary SPICE kernel path
        :param endianness: Required endianness of the binary SPICE kernel file.

        :return: Error message, if error present. Otherwise, None.
        """
        # Check the file architecture of the SPICE kernel. If the kernel is not
        # based on DAF or DAS architecture, report the error.
        arch, _ = spiceypy.getfat(path)
        if arch not in ['DAF', 'DAS']:
            return 'The binary kernel does not have a DAF or DAS architecture.'

        # At this point, we can check the endianness of the binary SPICE kernel.
        # Since there is no SPICE API to perform this check, we will try to open
        # the file for writing and immediately after, close it. SPICE will
        # produce a SPICE(UNSUPPORTEDBFF) error if the endianness of the file
        # does not correspond to the endianness of the platform in which NPB
        # is executed.
        try:
            if arch == "DAF":
                handle = spiceypy.dafopw(path)
                spiceypy.dafcls(handle)
            else:  # DAS architecture
                handle = spiceypy.dasopw(path)
                spiceypy.dascls(handle)

            # Getting to this point means that the file and the platform in
            # which NPB is executed have the same architecture.
            equal_endianness = True

        except SpiceUNSUPPORTEDBFF:
            # There is no need to call the SPICE API to close the binary SPICE
            # kernel, since the open process did not complete. The open call
            # retuning with SPICE(UNSUPPORTEDBFF) indicates that the file and
            # the platform in which NPB is executed have different architecture.
            equal_endianness = False

        # By comparing the result of comparing the platform byte order to the
        # expected file endianness, and the result of the previous analysis,
        # we can find out if the file has the expected endianness.
        if (endianness == sys.byteorder) != equal_endianness:
            return ("The kernel cannot be loaded because of its endianness. "
                    "Use NAIF's utility BINGO to convert the file.")

        return None

    @staticmethod
    def _check_badchar(file: str) -> list[str]:
        """Check NON-ASCII characters for a file.

        :param file: Path to file to check
        :return: Resulting error messages
        """
        error = []
        line_num = 1
        with open(file, "r", encoding='utf-8') as f:
            for line in f:
                if not line.isascii():
                    char_count = 0
                    badchars = []
                    for char in line:
                        if not char.isascii():
                            badchars.append(char_count)
                        char_count += 1

                    error.append(f"NON-ASCII character(s) in line {line_num}:")
                    error.append(f"{line.rstrip()}")
                    badchar_line = " " * len(line.rstrip())
                    for badchar in badchars:
                        badchar_line = (
                            badchar_line[:badchar] + "^"
                            + badchar_line[badchar + 1 :]
                        )
                    error.append(badchar_line)
                line_num += 1

        return error

    @staticmethod
    def _check_permissions(path: str) -> None:
        """Check that the account running NPB can read a file.

        :param path: Path to the file to check.
        :raises NPBError: if the file is not readable.
        """
        # Open for reading instead of inspecting the permission bits, so the
        # check works on Unix and Windows. Binary mode because the file may be
        # either text or binary.
        try:
            with Path(path).open('rb') as f:
                f.read(0)

        except PermissionError:
            raise NPBError(
                f"File {path} is not readable by the account that runs NPB. "
                f"Update permissions."
            )
